"""
Pydantic request/response schemas for the Clinical Risk Prediction API.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


# ──────────────────────────────────────────────
# Prediction
# ──────────────────────────────────────────────

class PredictionInput(BaseModel):
    """Input features for cardiovascular risk prediction (UCI Cleveland schema)."""

    age: float = Field(..., ge=1, le=120, description="Age in years")
    sex: float = Field(..., ge=0, le=1, description="Sex: 1=male, 0=female")
    cp: float = Field(..., ge=1, le=4, description="Chest pain type: 1=typical angina, 2=atypical, 3=non-anginal, 4=asymptomatic")
    trestbps: float = Field(..., ge=50, le=300, description="Resting blood pressure (mm Hg)")
    chol: float = Field(..., ge=100, le=700, description="Serum cholesterol (mg/dl)")
    fbs: float = Field(..., ge=0, le=1, description="Fasting blood sugar > 120 mg/dl: 1=true, 0=false")
    restecg: float = Field(..., ge=0, le=2, description="Resting ECG: 0=normal, 1=ST-T abnormality, 2=LV hypertrophy")
    thalach: float = Field(..., ge=50, le=250, description="Maximum heart rate achieved (bpm)")
    exang: float = Field(..., ge=0, le=1, description="Exercise-induced angina: 1=yes, 0=no")
    oldpeak: float = Field(..., ge=0.0, le=10.0, description="ST depression induced by exercise relative to rest")
    slope: float = Field(..., ge=1, le=3, description="Slope of peak exercise ST segment: 1=up, 2=flat, 3=down")
    ca: float = Field(..., ge=0, le=3, description="Number of major vessels (0–3) coloured by fluoroscopy")
    thal: float = Field(..., description="Thallium scan result: 3=normal, 6=fixed defect, 7=reversable defect")

    @field_validator("thal")
    @classmethod
    def validate_thal(cls, v: float) -> float:
        if v not in (3, 6, 7):
            raise ValueError("thal must be 3 (normal), 6 (fixed defect), or 7 (reversable defect)")
        return v

    model_config = {"json_schema_extra": {
        "example": {
            "age": 63, "sex": 1, "cp": 1, "trestbps": 145, "chol": 233,
            "fbs": 1, "restecg": 2, "thalach": 150, "exang": 0,
            "oldpeak": 2.3, "slope": 3, "ca": 0, "thal": 6,
        }
    }}


class PredictionResponse(BaseModel):
    predicted_class: int
    probability_positive_class: Optional[float]
    model_name: str
    model_version: str
    interpretation: str
    disclaimer: str = (
        "This output is a dataset classification result from a machine learning model "
        "trained on the UCI Cleveland Heart Disease dataset. It is NOT a clinical diagnosis "
        "or validated cardiovascular risk assessment. Consult a qualified healthcare professional "
        "for medical advice."
    )


class ExplainRequest(BaseModel):
    input_data: PredictionInput
    model_name: Optional[str] = None


class ShapContribution(BaseModel):
    feature: str
    shap_value: float
    feature_value: float
    direction: str


class ExplainResponse(BaseModel):
    status: str
    contributions: List[ShapContribution] = []
    base_value: Optional[float] = None
    message: Optional[str] = None
    global_importance: Optional[List[Dict[str, Any]]] = None
    caveat: str = (
        "SHAP feature contributions indicate the influence of each feature on this specific "
        "model prediction. They do not establish medical causation. The model was trained on "
        "the UCI Cleveland dataset and is for educational use only."
    )


# ──────────────────────────────────────────────
# RAG / Chat
# ──────────────────────────────────────────────

class RetrieveRequest(BaseModel):
    query: str = Field(..., min_length=1, max_length=1000)
    top_k: Optional[int] = Field(default=5, ge=1, le=20)


class PassageResult(BaseModel):
    text: str
    title: str
    organization: str
    url: str
    section: str
    similarity_score: float


class RetrieveResponse(BaseModel):
    query: str
    passages: List[PassageResult]
    n_retrieved: int


class ChatMessage(BaseModel):
    role: str = Field(..., description="Role of the sender: 'user' or 'assistant'")
    content: str = Field(..., description="Content of the message")


class ChatRequest(BaseModel):
    query: str = Field(..., min_length=1, max_length=2000)
    top_k: Optional[int] = Field(default=5, ge=1, le=20)
    history: Optional[List[ChatMessage]] = Field(default=None, description="Previous conversation turns for conversational memory")


class ChatResponse(BaseModel):
    query: str
    answer: Optional[str]
    passages: List[PassageResult]
    sources_used: List[str]
    provider: str
    retrieval_available: bool
    llm_available: bool
    error: Optional[str] = None
    disclaimer: str = (
        "This response is generated by an AI language model for educational purposes only. "
        "It is not medical advice. Consult a qualified healthcare professional for personal "
        "health decisions."
    )


# ──────────────────────────────────────────────
# Model info / metrics
# ──────────────────────────────────────────────

class ModelInfoResponse(BaseModel):
    selected_model: str
    available_models: List[str]
    model_version: str
    ready: bool
    error: Optional[str] = None
    training_date: Optional[str] = None
    dataset: Optional[Dict[str, Any]] = None


class MetricsResponse(BaseModel):
    models: Dict[str, Any]


# ──────────────────────────────────────────────
# Health
# ──────────────────────────────────────────────

class HealthResponse(BaseModel):
    status: str
    model_ready: bool
    retrieval_ready: bool
    llm_ready: bool
    version: str = "1.0.0"


# ──────────────────────────────────────────────
# Knowledge sources
# ──────────────────────────────────────────────

class KnowledgeSource(BaseModel):
    title: str
    organization: str
    url: str
    section: str
    retrieved_date: str


class KnowledgeSourcesResponse(BaseModel):
    sources: List[KnowledgeSource]
    total: int
